def save():
    global day
    global name
    global level
    global mood
    global loss
    global win
    with open("pokemondata.txt","w") as save_info:
        save_info.write(str(day) + "\n")
        save_info.write(str(name)+ "\n")
        save_info.write(str(level)+ "\n")
        save_info.write(str(mood)+ "\n")
        save_info.write(str(loss)+ "\n")
        save_info.write(str(win)+ "\n")
    print("game saved successfully!")

def load_save():
    global day
    global name
    global level
    global mood
    global loss
    global win
    with open("pokemondata.txt", "r") as save_info:
        day = int(save_info.readline().strip())
        name = save_info.readline().strip()
        level = int(save_info.readline().strip())
        mood = save_info.readline().strip()
        loss = int(save_info.readline().strip())
        win = int(save_info.readline().strip())
    print("game loaded successfully!")

